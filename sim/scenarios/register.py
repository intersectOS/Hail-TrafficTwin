"""Generate docs/assumptions-trackB.md from the Track B YAML files (single source of truth).

python -m sim.scenarios register          # rewrite the file
python -m sim.scenarios register --check  # fail if it is out of date
"""

from __future__ import annotations

from pathlib import Path

from sim.common import REPO_ROOT, load_yaml, rel
from sim.vtypes.schema import Param, params_in

REGISTER_FILE = REPO_ROOT / "docs" / "assumptions-trackB.md"
SOURCES = (
    "sim/vtypes/types.yaml",
    "sim/vtypes/mix_default.yaml",
    "sim/events/weather.yaml",
    "sim/events/events.yaml",
    "sim/scenarios/kpis.yaml",
    # integration (B-D-024, B-D-031): strategist and evacuation rows join the track register
    "strategist/strategist.yaml",
    "strategist/weights.yaml",
    "sim/scenarios/evac_settings.yaml",
)
# Rows whose values live in a file another agent maintains (data/jeddah_flood_sites.yaml).
EXTRA_ROWS = (
    "| A-event-flood-radius | flood site radius_m defaults | 80 / 120-150 / 300-500 / 600-800 "
    "| m | per site kind | Single underpass 80 m (depressed section + intersection above); long "
    "tunnels or paired underpasses 120-150 m; wadi crossings 300-500 m; area-only (district) sites "
    "600-800 m. Described in the data/jeddah_flood_sites.yaml header; not calibrated against flood "
    "extents | assumed | data/jeddah_flood_sites.yaml, sim/events/flood.py |",
)
HEADER = """# Assumptions register: Track B (windows, events, strategist, evacuation)

Generated by `python -m sim.scenarios register` from the YAML files listed under "used in"; edit
the YAML, then regenerate (a test checks this file is current). Same format as
docs/assumptions.md; status `assumed` | `sourced` | `calibrated` (only M8 sets `calibrated`).
SUMO default values were read back from SUMO 1.28.0 via TraCI; they are model defaults, not
Jeddah observations, hence `assumed`. Citations marked "unverified" were quoted from memory and
not checked against the paper. All results are **synthetic demand, uncalibrated**; all event
files are fictional (PROJECT.md section 11).

| id | parameter | value | unit | range | source or assumption | status | used in |
|---|---|---|---|---|---|---|---|
"""


def _cell(text: str) -> str:
    return str(text).replace("|", "/").replace("\n", " ")


LINK_ROWS_FILE = "sim/config/link_assumptions.yaml"


def link_rows() -> tuple[str, ...]:
    """Tier link and window-build rows (sim.link reads the values from sim/config/link.yaml)."""
    keys = ("id", "parameter", "value", "unit", "range", "assumption", "status", "used_in")
    data = load_yaml(REPO_ROOT / LINK_ROWS_FILE)
    return tuple("| " + " | ".join(_cell(r[k]) for k in keys) + " |" for r in data["rows"])


def rows() -> list[tuple[str, str]]:
    out: list[tuple[str, str]] = []
    seen: dict[str, str] = {}
    for src in SOURCES:
        tree = load_yaml(REPO_ROOT / src)
        for path, raw in params_in(tree):
            p = Param.model_validate(raw)
            if p.id in seen:
                raise ValueError(f"duplicate assumption id {p.id} ({seen[p.id]} and {path})")
            seen[p.id] = path
            name = path.replace("types.", "").replace(".params.", ".").replace("presets.", "rain.")
            text = p.source or ""
            if p.assumption:
                text = f"{text}; {p.assumption}" if text else p.assumption
            out.append(
                (
                    p.id,
                    f"| {p.id} | {_cell(name)} | {_cell(p.value)} | {_cell(p.unit)} | "
                    f"{_cell(p.range_text())} | {_cell(text)} | {p.status} | {src} |",
                )
            )
    return out


def _key(pid: str) -> tuple[str, int, str]:
    area, _, num = pid[2:].partition("-")
    return (area, int(num) if num.isdigit() else 10**6, num)


def render() -> str:
    body = [r for _, r in sorted(rows(), key=lambda kv: _key(kv[0]))]
    return HEADER + "\n".join([*body, *EXTRA_ROWS, *link_rows()]) + "\n"


def all_ids() -> set[str]:
    return {pid for pid, _ in rows()} | {
        r.split("|")[1].strip() for r in (*EXTRA_ROWS, *link_rows())
    }


def write(path: Path = REGISTER_FILE) -> Path:
    path.write_text(render())
    return path


def is_current(path: Path = REGISTER_FILE) -> bool:
    return path.exists() and path.read_text() == render()


def describe() -> str:
    return f"{len(all_ids())} assumptions in {rel(REGISTER_FILE)}"
