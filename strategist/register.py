"""Render the strategist's registered parameters (strategist/*.yaml) as an assumptions table.

    python -m strategist.register          # rewrite the block in docs/strategist.md
    python -m strategist.register --check  # exit 1 if the block is out of date

Same row format as docs/assumptions-trackB.md. That file is generated verbatim by
`python -m sim.scenarios register` from a fixed source list (and a test compares it byte for
byte), so the M6 rows live in a generated block of docs/strategist.md until the integration adds
strategist/strategist.yaml and strategist/weights.yaml to sim.scenarios.register.SOURCES.
"""

from __future__ import annotations

from pathlib import Path

import typer

from sim.common import REPO_ROOT, load_yaml
from sim.vtypes.schema import Param, params_in

DOC = REPO_ROOT / "docs" / "strategist.md"
SOURCES = ("strategist/strategist.yaml", "strategist/weights.yaml")
BEGIN = "<!-- BEGIN M6 assumptions: generated by `python -m strategist.register`, do not edit -->"
END = "<!-- END M6 assumptions -->"
HEAD = (
    "| id | parameter | value | unit | range | source or assumption | status | used in |\n"
    "|---|---|---|---|---|---|---|---|\n"
)


def _cell(text: object) -> str:
    return str(text).replace("|", "/").replace("\n", " ")


def rows() -> list[tuple[str, str]]:
    out: list[tuple[str, str]] = []
    seen: set[str] = set()
    for src in SOURCES:
        tree = load_yaml(REPO_ROOT / src)
        tree = {k: v for k, v in tree.items() if k != "model"}
        for path, raw in params_in(tree):
            p = Param.model_validate(raw)
            if p.id in seen:
                raise ValueError(f"duplicate assumption id {p.id} in {src}")
            seen.add(p.id)
            text = p.source or ""
            if p.assumption:
                text = f"{text}; {p.assumption}" if text else p.assumption
            out.append(
                (
                    p.id,
                    f"| {p.id} | {_cell(path.replace('weights.', ''))} | {_cell(p.value)} | "
                    f"{_cell(p.unit)} | {_cell(p.range_text())} | {_cell(text)} | "
                    f"{p.status} | {src} |",
                )
            )
    return out


def ids() -> set[str]:
    return {pid for pid, _ in rows()}


def block() -> str:
    body = "\n".join(r for _, r in sorted(rows(), key=lambda kv: int(kv[0].rsplit("-", 1)[1])))
    return f"{BEGIN}\n{HEAD}{body}\n{END}"


def render(text: str) -> str:
    if BEGIN in text and END in text:
        pre, rest = text.split(BEGIN, 1)
        _, post = rest.split(END, 1)
        return pre + block() + post
    return text.rstrip("\n") + "\n\n" + block() + "\n"


def is_current(doc: Path = DOC) -> bool:
    return doc.exists() and render(doc.read_text()) == doc.read_text()


def write(doc: Path = DOC) -> None:
    doc.write_text(render(doc.read_text() if doc.exists() else ""))


app = typer.Typer(add_completion=False, help=__doc__)


@app.command()
def main(check: bool = typer.Option(False)) -> None:
    if check:
        if not is_current():
            typer.echo(
                "docs/strategist.md M6 assumptions are out of date: python -m strategist.register"
            )
            raise typer.Exit(code=1)
        typer.echo(f"current: {len(rows())} M6 assumptions in docs/strategist.md")
        return
    write()
    typer.echo(f"wrote {len(rows())} M6 assumptions to docs/strategist.md")


if __name__ == "__main__":
    app()
